// Builds lib/homeSample.json: the homepage sample result, derived ONLY from the saved real
// RingConn scan (real accepted reviews, real verdict). Re-run to refresh; never hand-edit.
import fs from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const jiti = require("jiti")(import.meta.url.replace("file://", ""), { alias: { "@": new URL("..", import.meta.url).pathname } });
const env = JSON.parse(fs.readFileSync(process.argv[2] || "/private/tmp/reviewintel-ui-result.json", "utf8"));
const { deriveShopperAnswer } = jiti("../lib/shopperAnswer.ts");
const r = env.result;
const a = deriveShopperAnswer(r);
const distinct = (points) => { const seen = new Set(); return points.filter(p => p.quote && !seen.has(p.quote) && seen.add(p.quote)); };
const sample = {
  source: "Saved ReviewIntel scan (real Amazon.ca buyer reviews); generated by scripts/reviewintel-home-sample.mjs",
  scanId: env.scanId || r.scanId || null,
  product: r.product?.title || r.productName,
  listingUrl: r.exactListingUrl || null,
  label: a.label, kind: a.kind, why: a.why, score: a.score,
  confidencePercent: a.confidencePercent, confidenceWords: a.confidenceWords,
  reviewCount: a.reviewCount, sources: a.sources,
  loves: distinct(a.loves).slice(0, 2), complaints: distinct(a.complaints).slice(0, 2),
};
fs.writeFileSync(new URL("../lib/homeSample.json", import.meta.url), JSON.stringify(sample, null, 2) + "\n");
console.log(JSON.stringify(sample, null, 2).slice(0, 1500));
